// Embed fonts/font0.ttf and its measured advances in src/fonts/font0.ts
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const font = readFileSync(new URL("fonts/font0.ttf", root)).toString("base64");
const advances = JSON.parse(
  readFileSync(new URL("fonts/font0-advances.json", root), "utf8")
);

// Advances as "codePoint:width" pairs; characters without a glyph are left out
const table = Object.entries(advances)
  .filter(([, width]) => width !== null)
  .map(([code, width]) => `${Number(code).toString(36)}:${width}`)
  .join(",");

writeFileSync(
  new URL("src/fonts/font0.ts", root),
  `// Generated by scripts/generate-fonts.mjs from fonts/font0.ttf (Archivo, SIL Open
// Font License 1.1, see fonts/OFL.txt) and fonts/font0-advances.json. Don't edit.

/** The font file, base64-encoded */
export const font0Data =
  "${font}";

/** Advance widths at ^A0N,100,100 by code point, as base-36 code:width pairs */
export const font0Advances = "${table}";
`
);
console.log(
  `font0.ts: ${font.length} base64 characters, ${
    table.split(",").length
  } advances`
);
