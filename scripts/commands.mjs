// Generates the supported commands table from the code: the docs page
// lists every command, the core README a summary per category.
// Usage: node scripts/commands.mjs [--check]  (after pnpm build)
//
// With --check, it exits with an error instead of writing when a file is
// out of date, for CI.
import { readFileSync, writeFileSync } from "node:fs";
import commands from "../packages/zpl/build/commands.js";
import { parsedCommands } from "../packages/zpl/build/parse.js";
import { renderedCommands } from "../packages/render/build/support.js";

const root = new URL("../", import.meta.url);
const docsPage = new URL("apps/site/content/docs/commands.mdx", root);
const readme = new URL("packages/zpl/README.md", root);
const docsUrl = "https://zplkit.fingal.dev/docs/commands";

const groups = {
  "Labels and formats": ["^XA", "^XZ", "^LH", "^LL", "^LR", "^LS", "^LT", "^PW", "^PO", "^PM", "^DF", "^XF", "^MU", "^CC", "~CC", "^CD", "~CD", "^CT", "~CT"],
  "Text and fonts": ["^A", "^A@", "^CF", "^CI", "^CW", "^FB", "^FH", "^SE", "~DB", "~DE", "~DS", "~DT", "~DU"],
  "Graphics and images": ["~DG", "~DY", "~EG", "~DN", "^XG", "^IL", "^IM", "^IS", "^ID", "^HG", "^HY"],
};

/** Barcodes, fields and graphics go by prefix; everything else is printer setup */
const categoryOf = (code) => {
  for (const [name, codes] of Object.entries(groups)) {
    if (codes.includes(code)) return name;
  }
  if (code.startsWith("^B")) return "Barcodes";
  if (code.startsWith("^G")) return "Graphics and images";
  if (code.startsWith("^F") || code === "^SF" || code === "^SN") return "Fields";
  return "Printer and media";
};

const categories = [
  "Labels and formats",
  "Fields",
  "Text and fonts",
  "Graphics and images",
  "Barcodes",
  "Printer and media",
];

const parsed = new Set(parsedCommands);
const rendered = new Set(renderedCommands);
const all = Object.entries(commands).map(([code, name]) => ({
  code,
  name,
  category: categoryOf(code),
  parsed: parsed.has(code),
  rendered: rendered.has(code),
}));
const supported = all.filter((command) => command.parsed);

const page = [
  "---",
  "title: Supported commands",
  "description: Which ZPL commands zplkit reads, writes and draws.",
  "---",
  "",
  "{/* Generated by scripts/commands.mjs from the code; don't edit by hand */}",
  "",
  `zplkit reads and writes ${supported.length} of the ${all.length} commands in Zebra's ZPL II Programming Guide.`,
  "",
  "- **Read and write**: `parse()` turns the command into a typed node, and labels can be built with it. Other commands are kept as raw text, so nothing is lost, and can be added with `raw()`.",
  "- **Drawn**: [`@zplkit/render`](/docs/rendering) and the [preview](/docs/preview) show what it does. Printer settings, like print speed, don't change the label's image.",
  "",
  ...categories.flatMap((category) => {
    const rows = all.filter((command) => command.category === category);
    const setup = category === "Printer and media";
    return [
      `## ${category}`,
      "",
      "| Command | Name | Read and write | Drawn |",
      "| --- | --- | :-: | :-: |",
      ...rows.map(
        ({ code, name, parsed, rendered }) =>
          `| \`${code}\` | ${name.replace(/\|/g, "\\|")} | ${parsed ? "✓" : ""} | ${rendered ? "✓" : setup ? "–" : ""} |`
      ),
      "",
    ];
  }),
].join("\n");

const summary = [
  "<!-- commands:start (generated by scripts/commands.mjs) -->",
  "",
  `\`@zplkit/core\` reads and writes ${supported.length} of the ${all.length} commands in Zebra's ZPL II Programming Guide. Other commands are kept as they are by \`parse()\` and can be added with \`raw()\`. The [full table](${docsUrl}) also shows which ones the renderer draws.`,
  "",
  "| Category | Supported |",
  "| --- | --- |",
  ...categories.map((category) => {
    const rows = all.filter((command) => command.category === category);
    const codes = rows.filter((command) => command.parsed).map(({ code }) => `\`${code}\``);
    return `| ${category} (${codes.length} of ${rows.length}) | ${codes.join(" ") || "–"} |`;
  }),
  "",
  "<!-- commands:end -->",
].join("\n");

const current = readFileSync(readme, "utf8");
const start = current.indexOf("<!-- commands:start");
const end = current.indexOf("<!-- commands:end -->");
if (start < 0 || end < 0) throw new Error("README.md has no commands markers");
const newReadme =
  current.slice(0, start) + summary + current.slice(end + "<!-- commands:end -->".length);

const outdated = [];
for (const [file, content] of [
  [docsPage, page],
  [readme, newReadme],
]) {
  let existing = "";
  try {
    existing = readFileSync(file, "utf8");
  } catch {
    // Not generated yet
  }
  if (existing === content) continue;
  if (process.argv.includes("--check")) outdated.push(file.pathname);
  else writeFileSync(file, content);
}

if (outdated.length) {
  console.error(
    `Out of date, run node scripts/commands.mjs:\n${outdated.join("\n")}`
  );
  process.exit(1);
}
